"""Write the simulator's visual meshes (STL) and their manifest (meshes.yaml)."""

from __future__ import annotations

from pathlib import Path

import yaml
from build123d import export_stl

from bemu_cad.body import build_body
from bemu_cad.components import Components
from bemu_cad.leg import build_leg
from bemu_cad.visual import build_visuals
from bemu_params import RobotParams


def export_visuals(
    params: RobotParams, components: Components, out_dir: Path, *, allowance: float | None = None
) -> dict[str, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    leg = (
        build_leg(params, components)
        if allowance is None
        else build_leg(params, components, allowance=allowance)
    )
    body = build_body(params, components, leg)
    meshes, manifest = build_visuals(leg, body)
    written = {}
    for stem, solid in meshes.items():
        path = out_dir / f"{stem}.stl"
        if not export_stl(solid, str(path)):
            raise ValueError(f"could not write {path}")
        written[f"{stem}.stl"] = path
    manifest_path = out_dir / "meshes.yaml"

    class NoAliases(yaml.SafeDumper):
        def ignore_aliases(self, data):
            return True

    manifest_path.write_text(
        "# Generated by tools/generate_cad.py: visual meshes for the simulator and RViz.\n"
        + yaml.dump(manifest, Dumper=NoAliases, sort_keys=False, default_flow_style=None),
        encoding="utf-8",
    )
    written["meshes.yaml"] = manifest_path
    return written
